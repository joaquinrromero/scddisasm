"""Bakes the data for the Markey-style Mode 7 floor demo (stage 1).

Architecture: RAM streaming texture.
  - Angle tables: camera-relative texel offsets for rows R0..95, same format
    as before but W is computed from the actual footprint at R0=55.
  - Stamp pixels (ROM): FloorStamps — raw 4bpp stamp data, one stamp = 512 B,
    same layout as the SCD disasm originals.
  - Stamp map (ROM): FloorStampMap — full 128x128 word map of the stage.
  - Packed stamp pixels (ROM): FloorStampsPacked — stamps pre-converted to
    4bpp packed row-major (16 bytes/row, 32 rows = 512 B/stamp) so the texture
    rebuild loop can copy a row with a single movem.l.

At runtime, a 224x224 4bpp-packed texture lives in RAM (FloorTex, ~25 KB).
BuildTex fills it from the stamp map on init; UpdateTexture rewrites one
column and one row when the camera crosses a stamp boundary (every 32 px).
"""
import struct, sys, os
import numpy as np
from ref import *

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
OUT = sys.argv[1] if len(sys.argv) > 1 else "src/MD Port/Floor Demo"
NANG = int(os.environ.get("NANG", "32")); R0 = int(os.environ.get("R0", "55"))
Z = 0x160; SEG = 16
X0_CAM = 0x540; Y0_CAM = 0x520           # camera start in map pixels
os.makedirs(OUT, exist_ok=True)

S, M = decode_stage(1)

# ---- measure footprint R ----
maxR_pre = 0
for a in range(NANG):
    yaw = a * 512 // NANG
    tab = trace_table(0, 0, Z, 0x80, yaw)
    i = np.arange(256)
    for r in range(R0, 96):
        xs, ys, dx, dy = tab[r]
        X = (xs*256 + i*dx) >> 11; Y = (ys*256 + i*dy) >> 11
        maxR_pre = max(maxR_pre, int(np.abs(X).max()), int(np.abs(Y).max()))
W = H = int(np.ceil((maxR_pre * 2 + 1) / 32)) * 32
assert W == 224, f"Expected W=224, got {W}"

# ---- packed stamps (ROM): 4bpp row-major, 16 bytes/row x 32 rows = 512 B/stamp ----
# S[sid] is shape (32,32) uint8 with values 0-15.
# Packed: each byte = (S[row,col*2] << 4) | S[row, col*2+1]  (big-endian nibbles, row-major)
nstamps = S.shape[0]  # includes stamp 0 (blank)
packed_stamps = np.zeros((nstamps, 32, 16), np.uint8)
packed_stamps[:, :, :] = (S[:, :, 0::2] << 4) | S[:, :, 1::2]
open(f"{OUT}/stamps_packed.bin", "wb").write(packed_stamps.tobytes())

# ---- stamp map (ROM): full 128x128, big-endian words ----
open(f"{OUT}/stamp_map.bin", "wb").write(M.astype(">u2").tobytes())

# ---- per-angle tables ----
# Offsets are relative to camera; tex coords = (cam + rel) mod W.
# W=224 so all offsets fit in a signed word with room to spare.
i = np.arange(256)
angles = bytearray(); offs = []; maxrel = 0; maxR = 0
fwd = []
for a in range(NANG):
    yaw = a * 512 // NANG
    tab = trace_table(0, 0, Z, 0x80, yaw)
    offs.append(len(angles))
    for r in range(R0, 96):
        xs, ys, dx, dy = tab[r]
        X = (xs*256 + i*dx) >> 11; Y = (ys*256 + i*dy) >> 11
        maxR = max(maxR, int(np.abs(X).max()), int(np.abs(Y).max()))
        L = Y * W + X                        # offset in texture (can be negative / > W*W)
        for s in range(256 // SEG):
            seg = L[s*SEG:(s+1)*SEG]
            # Take every other pixel (even pixels only) — packed format: 2 px per byte.
            # We need offsets for bytes 0..7 of the segment (pixel 0,2,4,6,8,10,12,14).
            seg_bytes = seg[0::2]            # shape (8,): one offset per packed byte
            base_packed = int(seg_bytes[0]) >> 1
            rel_packed = [int(seg_bytes[i] - seg_bytes[0]) >> 1 for i in range(1, 8)]
            maxrel = max(maxrel, max(abs(r) for r in rel_packed))
            assert all(abs(r) < 32768 for r in rel_packed), ("segment rel overflow", a, r, s)
            angles += struct.pack(">l", base_packed) + struct.pack(">7h", *rel_packed)
    cx_ = lambda r: ((tab[r][0]*256 + 128*tab[r][2]) >> 11, (tab[r][1]*256 + 128*tab[r][3]) >> 11)
    f = np.array(cx_(R0 + (96-R0)//4), float) - np.array(cx_(95), float)
    f = f / np.hypot(*f) * 4
    fwd.append((int(round(f[0]*256)), int(round(f[1]*256))))
open(f"{OUT}/angles.bin", "wb").write(bytes(angles))
open(f"{OUT}/forward.bin", "wb").write(b"".join(struct.pack(">hh", *f) for f in fwd))
with open(f"{OUT}/angle_dir.inc", "w") as f:
    for o in offs: f.write("\tdc.l\tFloorAngles+%d\n" % o)

rows = 96 - R0; per_angle = rows * (256 // SEG) * (4 + 14)   # 1 longword + 7 words per seg
tex_ram = W * W // 2          # 4bpp packed, 1 copy in RAM
with open(f"{OUT}/params.inc", "w") as f:
    f.write(f"""\t; Auto-generated by bake_floor_demo.py — do not edit
FD_W\t\tEQU\t{W}\t\t\t; Texture width/height in pixels
FD_WPACKED\tEQU\t{W//2}\t\t\t; Texture row stride in bytes (4bpp packed)
FD_TEXSIZE\tEQU\t{tex_ram}\t\t\t; RAM texture size in bytes ({tex_ram//1024} KB)
FD_WSTAMPS\tEQU\t{W//32}\t\t\t; Texture width/height in stamps
FD_R0\t\tEQU\t{R0}\t\t\t; First rendered row
FD_ROWS\t\tEQU\t{rows}
FD_NANG\t\tEQU\t{NANG}
FD_NSTAMPS\tEQU\t{nstamps}\t\t\t; Total stamps in ROM
FD_START\tEQU\t{W//2}\t\t\t; Camera start pixel (= W/2 inside texture)
FD_STARTSX\tEQU\t{(X0_CAM - W//2) % 4096}\t\t; Map pixel of tex col 0 at startup
FD_STARTSY\tEQU\t{(Y0_CAM - W//2) % 4096}\t\t; Map pixel of tex row 0 at startup
FD_STARTMX\tEQU\t{((X0_CAM - W//2) % 4096) >> 5}\t\t; Map stamp of tex col 0 at startup
FD_STARTMY\tEQU\t{((Y0_CAM - W//2) % 4096) >> 5}\t\t; Map stamp of tex row 0 at startup
FD_STARTCAMX\tEQU\t${X0_CAM:X}\t\t\t; Camera start X in map pixels
FD_STARTCAMY\tEQU\t${Y0_CAM:X}\t\t\t; Camera start Y in map pixels
""")
print(f"R0={R0}, NANG={NANG}, rows {R0}..95 ({rows}), footprint R={maxR}, texture W={W} ({W//32} stamps)")
print(f"angle tables: {len(angles)//1024} KB ({per_angle//1024} KB/angle x {NANG})")
print(f"stamps packed: {nstamps} x 512 B = {nstamps*512//1024} KB")
print(f"stamp map: 128x128 x 2 B = {128*128*2//1024} KB")
print(f"RAM texture: {W}x{W} 4bpp packed = {tex_ram//1024} KB")
print(f"Total ROM: {(len(angles) + nstamps*512 + 128*128*2)//1024} KB")
print(f"Max segment relative offset: {maxrel}")
