#!/usr/bin/env python3
"""
Genera "MD Port/Zones/Zone Table.asm": un bloque de punteros por (acto, zona de tiempo), en el orden de zoneVars
(Level/_Definitions.inc). Indice = acto*4 + {0 pasado, 1 presente, 2 buen futuro, 3 mal futuro}.
Fuentes de cada bloque:  PPZ Acto 1 -> MD Port/Zones/<Zona>/_symbols.txt (RENAMED: prefijo Zona_), Presente = motor;
rondas extraidas (R12A...) -> MD Port/Zones/<R>/_symbols.txt (MAP: simbolo=etiqueta).  Lo que una zona no define usa el
simbolo del motor. Huecos (zonas sin portar) usan el Presente del Acto 1.   Uso (desde src/): python3 ../tools/make_zone_table.py
"""
import re, os
ACTS = [("Past", "Present", "GoodFuture", "BadFuture"), ("R12B", "R12A", "R12C", "R12D"), (None, None, "R13C", "R13D")]
defs = open("Level/_Definitions.inc").read().split("zoneVars\t\trs.b\t0")[1].split("zoneVarsEnd")[0]
syms = [m.group(2) for m in re.finditer(r"^(z\w+)\s+rs\.l\s+1\s*;\s*(\w+)", defs, re.M)]
ALIAS = {}
if os.path.exists("MD Port/Zones/Zone Aliases.txt"):
    ALIAS = dict(l.split("=", 1) for l in open("MD Port/Zones/Zone Aliases.txt").read().split("\n") if "=" in l)
def block(z):
    b = block0(z)
    if b:
        for s in syms:
            if f"{z}.{s}" in ALIAS: b[s] = ALIAS[f"{z}.{s}"]
    return b
def block0(z):
    if z == "Present": return {s: s for s in syms}
    f = f"MD Port/Zones/{z}/_symbols.txt"
    if not os.path.exists(f): return None
    t = open(f).read()
    if t.startswith("MAP"):
        m = dict(l.split("=", 1) for l in t.split("\n")[1:] if "=" in l)
        return {s: m.get(s, s) for s in syms}
    ren = set(t.split("RENAMED\n")[1].split("\n\n")[0].split("\n")); pre = z + "_"
    return {s: (pre + s if s in ren else s) for s in syms}
out = ["; -------------------------------------------------------------------------", "; Sonic CD Disassembly - Mega Drive port",
       "; -------------------------------------------------------------------------",
       "; Zone table (generated by tools/make_zone_table.py): one block of pointers per (act, time zone), in the",
       "; order of zoneVars. Index = act*4 + (0 past, 1 present, 2 good future, 3 bad future).",
       "; -------------------------------------------------------------------------", "", "ZoneTable:"]
blocks = []; names = []
for act in ACTS:
    for z in act:
        b = block(z) if z else None
        key = z if b else "Present"; names.append(key)
        if b and z not in [n for n, _ in blocks]: blocks.append((z, b))
        elif not b and "Present" not in [n for n, _ in blocks]: blocks.append(("Present", block("Present")))
out += [f"\tdc.l\tZoneData_{n}" for n in names] + [""]
for z, b in blocks:
    out.append(f"ZoneData_{z}:"); out += [f"\tdc.l\t{b[s]}" for s in syms]; out.append("")
open("MD Port/Zones/Zone Table.asm", "w", newline="\n").write("\n".join(out))
print(f"tabla: {len(syms)} simbolos, {len(blocks)} bloques distintos, {len(names)} entradas ({names})")
