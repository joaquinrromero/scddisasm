"""Mega Drive build for one generated level: Main file from the repo's PP port + asm68k + header fix."""
import os, re, struct

from .pipeline import asm68k

RAM_VARS = 0xFFFFC010          # RomVar slots (debugSpeed lives at $FFFFC000)
RAM_LIMIT = 0xFFFFC800


def make_main(src, level_asm, zone_name, act_name, rid, tz, good, romvars, zoneact):
    """Returns the text of 'MD Port/Main (<rid>).asm' derived from 'MD Port/Main.asm'."""
    t = open(os.path.join(src, 'MD Port', 'Main.asm'), encoding='utf-8', errors='ignore').read()

    def sub(old, new, count=1):
        nonlocal t
        if old not in t:
            raise RuntimeError('MD Port/Main.asm changed, cannot find: ' + old)
        t = t.replace(old, new, count)
    sub('; Standalone Mega Drive ROM: Palmtree Panic Act 1 (Present)',
        '; Standalone Mega Drive ROM: %s %s (%s) - generated by tools/mmd2md' % (zone_name, act_name.split(' ')[0] + ' ' + act_name.split(' ')[1], rid))
    sub('\tinclude\t"Level/Palmtree Panic/Act 1 Present.asm"', '\tinclude\t"%s"' % level_asm)
    tname = {0: 'TIME_PAST', 1: 'TIME_PRESENT', 2: 'TIME_FUTURE'}[tz]
    t = t.replace('TIME_PRESENT|$80', tname + '|$80')
    sub('\tmove.b\t#TIME_PRESENT,timeZone\n\trts',
        '\tmove.b\t#%s,timeZone\n\tmove.b\t#%d,goodFuture\n\tmove.w\t#$%04X,zoneAct\t\t\t; %s, act %s (the level engine dispatches by zone)\n%s\trts'
        % (tname, good, zoneact, zone_name, act_name.split(' ')[1],
           ''.join('\tmove.%s\t$%06X.l,RomVar_%06X.l\t\t; initial value of data the level writes to\n'
                   % ({1: 'b', 2: 'w', 4: 'l'}.get(size, 'l'), base, base) for base, (size, mem) in romvars.items() if size in (1, 2, 4))))
    # RAM slots for variables that live in the level's ROM area on the Sega CD
    eq = []
    ram = RAM_VARS
    for base, (size, mem) in romvars.items():
        if ram % 2:
            ram += 1
        eq.append('RomVar_%06X\tEQU\t$%08X\t\t; ROM data written by the level -> RAM' % (base, ram))
        ram += (size + 1) & ~1
    if ram > RAM_LIMIT:
        raise RuntimeError('too many ROM variables for the free RAM hole')
    if eq:
        sub('debugSpeed\tEQU\t$FFFFC000\t\t; Debug mode speed (long)',
            'debugSpeed\tEQU\t$FFFFC000\t\t; Debug mode speed (long)\n' + '\n'.join(eq))
    return t


def sizes(sz):
    return {1: 'b', 2: 'w', 4: 'l'}.get(sz, 'l')


def fix_header(path):
    d = bytearray(open(path, 'rb').read())
    if len(d) % 2:
        d.append(0)
    d[0x1A4:0x1A8] = struct.pack('>L', len(d) - 1)
    s = 0
    for i in range(0x200, len(d), 2):
        s = (s + (d[i] << 8 | d[i + 1])) & 0xFFFF
    d[0x18E:0x190] = struct.pack('>H', s)
    open(path, 'wb').write(d)
    return len(d), s


def build(repo, main_rel, out_rom):
    log = asm68k(repo, main_rel, out_rom, flags=['/e', 'MDPORT=1'])
    ok = os.path.exists(out_rom) and re.search(r'(^|[^0-9])0 error\(s\)', log)
    if not ok:
        raise RuntimeError('MD build failed:\n' + '\n'.join(l for l in log.splitlines() if 'rror' in l)[:1500])
    return fix_header(out_rom)
