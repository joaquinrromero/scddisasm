#!/usr/bin/env python3
"""mmd2md - Sonic CD round MMD  ->  split disassembly  ->  Mega Drive ROM.

    python tools/mmd2md/mmd2md.py tools/R31A__.MMD            # one round
    python tools/mmd2md/mmd2md.py tools/*.MMD --jobs 4         # every round, 4 zones at a time
    python tools/mmd2md/mmd2md.py tools/R41A__.MMD --no-md     # only decompile + split

For every MMD it
  1. traces the code (capstone, recursive descent) and classifies code/data,
  2. names routines/data by comparing with the Palmtree Panic build of this repo,
  3. writes  src/Level/<Zone>/<Act> <Time>.asm  plus  src/Level/<Zone>/Data/{Art,Level,Objects,Collision,Palette,Mappings,...},
  4. assembles it (asm68k) and checks it is byte-identical to the MMD (instructions asm68k cannot reproduce are
     emitted as raw bytes),
  5. builds  out/md/<ROM>.bin  (standalone Mega Drive ROM, same engine as the PP port) from "MD Port/Main.asm".
Needs: Python 3.8+, capstone (pip install capstone), asm68k (bin/asm68k.exe; wine on Linux/macOS).
"""
import argparse, glob, json, multiprocessing, os, sys, time, traceback

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from mmdlib import defs as defsmod, emit as emitmod, levelstruct, mdport, pipeline as P  # noqa: E402
from mmdlib.trace import Analysis  # noqa: E402

MARK = 'generated by tools/mmd2md'


def process(args):
    mmd, o = args
    repo = o['repo']; src = os.path.join(repo, 'src')
    info = P.parse_name(mmd)
    res = {'mmd': os.path.basename(mmd), 'ok': False}
    t0 = time.time()
    try:
        if o.get('zone') is not None:
            info = dict(info or {}, zone=o['zone'])
        if not info:
            raise RuntimeError('cannot tell round/act/time from the file name (expected R<round><act><A-D>__.MMD)')
        d = open(mmd, 'rb').read()
        ref = P.load_reference(repo, os.path.join(repo, 'out', 'misc', 'mmd2md_ref'))
        dfs = defsmod.parse(src)
        ana = Analysis(d).run()
        names, blobs = P.build_names(d, ana, ref)
        S = levelstruct.detect(d, ana, names, dfs[0])
        zone = P.ZONES[info['zone']]
        zone_dir = 'Level/' + zone
        tname, tz = P.TIMES[info['time']]
        act_name = 'Act %d %s' % (info['act'], tname)
        asm_rel = '%s/%s.asm' % (zone_dir, act_name)
        full = os.path.join(src, asm_rel)
        head = open(full, errors='ignore').read(300) if os.path.exists(full) else ''
        if head and MARK not in head and 'auto-disassembly (scdtrace/emit)' not in head:
            asm_rel = '%s/%s (Generated).asm' % (zone_dir, act_name)      # never overwrite hand-written source
        opts = emitmod.Opts()
        opts.zone_dir = zone_dir; opts.act = act_name; opts.act_short = 'Act %d' % info['act']
        opts.title = info['id']; opts.shared = P.shared_files(src); opts.store = P.Store(src, zone_dir)
        opts.romvars = P.find_romvars(ana, d)
        ok, raw, asm, files, einfo = P.roundtrip(repo, d, ana, names, blobs, S, dfs, opts, asm_rel, tag=info['id'],
                                                 log=lambda s: None)
        res.update(ok=ok, raw=len(raw), files=len(files), segments=len(einfo['segments']), asm=asm_rel,
                   romvars=len(opts.romvars), named=len(names))
        if not ok:
            raise RuntimeError('round trip is not byte-identical')
        if not o.get('no_md'):
            zoneact = (info['zone'] << 8) | (info['act'] - 1)
            good = 1 if info['time'] == 'C' else 0
            main_rel = 'MD Port/Main (%s).asm' % info['id']
            text = mdport.make_main(src, asm_rel, zone, act_name, info['id'], tz, good, opts.romvars, zoneact)
            open(os.path.join(src, main_rel), 'w', encoding='utf-8').write(text)
            out_dir = os.path.join(repo, 'out', 'md'); os.makedirs(out_dir, exist_ok=True)
            rom = os.path.join(out_dir, '%s %s %s.bin' % (info['id'], zone, act_name))
            size, chk = mdport.build(repo, main_rel, rom)
            res.update(rom=os.path.relpath(rom, repo), rom_size=size)
    except Exception as e:                                                   # noqa: BLE001
        res['error'] = str(e)
        if o.get('verbose'):
            traceback.print_exc()
    res['secs'] = round(time.time() - t0, 1)
    return res


def run_zone(group):
    return [process(a) for a in group]


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('mmd', nargs='+', help='round MMD files (globs allowed)')
    ap.add_argument('--repo', default=os.path.abspath(os.path.join(HERE, '..', '..')), help='repo root (default: this repo)')
    ap.add_argument('--no-md', action='store_true', help='stop after decompiling/splitting (no ROM)')
    ap.add_argument('--jobs', type=int, default=1, help='zones processed in parallel')
    ap.add_argument('--verbose', action='store_true')
    a = ap.parse_args()
    files = []
    for m in a.mmd:
        files += sorted(glob.glob(m)) or [m]
    o = {'repo': a.repo, 'no_md': a.no_md, 'verbose': a.verbose}
    groups = {}
    for f in files:
        i = P.parse_name(f)
        groups.setdefault(i['zone'] if i else -1, []).append((f, o))
    work = list(groups.values())
    if a.jobs > 1 and len(work) > 1:
        with multiprocessing.Pool(a.jobs) as pool:
            results = [r for grp in pool.imap_unordered(run_zone, work) for r in grp]
    else:
        results = [r for g in work for r in run_zone(g)]
    bad = 0
    for r in sorted(results, key=lambda r: r['mmd']):
        if r['ok'] and ('rom' in r or a.no_md):
            print('%-12s OK   %s%s' % (r['mmd'], r.get('rom', r.get('asm')), '   raw=%d' % r['raw'] if r.get('raw') else ''))
        else:
            bad += 1
            print('%-12s FAIL %s' % (r['mmd'], r.get('error', '?')))
    print('%d/%d ok' % (len(results) - bad, len(results)))
    return 1 if bad else 0


if __name__ == '__main__':
    sys.exit(main())
