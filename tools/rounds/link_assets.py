#!/usr/bin/env python3
"""Content-addressed asset linking for an extracted round (src/MD Port/Zones/<R>.asm).

 1. PLC lists are rebuilt from the round's MMD: every Nemesis art is cut out (exact size), hashed and linked to
    the asset that already exists in the ROM source with the same bytes (engine/other zones); if none exists it is
    written once to src/Level/_Art/Pool/<hash>.nem and added to src/Level/_Art/Pool.asm.
 2. Chunks of the zone file that are only `label: incbin file` and equal (bytes) an existing asset are removed and
    their references point to the shared label (no more R12A_Art_xxx copies).
usage (repo root): python3 tools/rounds/link_assets.py R12D"""
import sys, os, re, glob, struct, hashlib, collections
sys.path.insert(0, 'tools/rounds'); sys.path.insert(0, 'tools/mmd2md')
os.environ.setdefault('CCZ', '/home/claude/work/mdport/src/Level/')
import rlib
from mmdlib.nem import nem_size
R = sys.argv[1]
MMD = open(f'/home/claude/work/mdport/tools/{R}__.MMD', 'rb').read()
m = rlib.address_map(R, '/home/claude/work/mdport/src')
f = f'src/MD Port/Zones/{R}.asm'; t = open(f).read().replace('\r', '')
ZP = re.compile(r'^(?:R\d\d[A-D]|Past|GoodFuture|BadFuture)_')
SKIP = ('Collision Chaos', 'Metallic', 'Quartz', 'Stardust', 'Tidal', 'Wacky', '(Generated)', 'DA Garden', 'Main (R')
SYMS = set(re.findall(r'^[0-9A-F]{8}\s+([A-Za-z_][\w.]*):', open('src/MD Port/Main.lst', errors='replace').read(), re.M))
def included_files():
    """.asm files that really take part in the build (transitive `include`s of MD Port/Main.asm)"""
    seen, todo = set(), ['src/MD Port/Main.asm']
    while todo:
        p = todo.pop()
        if p in seen or not os.path.exists(p): continue
        seen.add(p)
        for mm in re.finditer(r'^\s*include\s+"([^"]+)"', open(p, errors='replace').read().replace('\r', ''), re.M | re.I):
            todo.append('src/' + mm[1].replace('\\', '/'))
    return seen
def build_index():
    idx = collections.defaultdict(list)
    for p in included_files():
        if p.endswith(f'/Zones/{R}.asm'): continue
        s = open(p, errors='replace').read().replace('\r', '')
        for mm in re.finditer(r'^([A-Za-z_]\w*):\s*(?:;[^\n]*)?\n\s*incbin\s+"([^"]+)"\s*$', s, re.M):
            q = 'src/' + mm[2]
            if os.path.exists(q): idx[hashlib.sha1(open(q, 'rb').read()).hexdigest()].append(mm[1])
    return {h: sorted(v, key=lambda n: (bool(ZP.match(n)), n))[0] for h, v in idx.items()}
IDX = build_index()
os.makedirs('src/Level/_Art/Pool', exist_ok=True)
poolf = 'src/Level/_Art/Pool.asm'
pool = open(poolf).read() if os.path.exists(poolf) else '; Shared art that only exists in some rounds (content-addressed, generated by tools/rounds/link_assets.py)\n'
def art_label(addr):
    o = addr - 0x200000
    r = nem_size(MMD, o)
    if not r: return None
    b = MMD[o:o + r[0]]; h = hashlib.sha1(b).hexdigest()
    if h in IDX: return IDX[h]
    lab = f'ArtPool_{h[:8]}'
    path = f'src/Level/_Art/Pool/{h[:8]}.nem'
    open(path, 'wb').write(b)
    global pool
    if lab + ':' not in pool: pool += f'{lab}:\n\tincbin\t"Level/_Art/Pool/{h[:8]}.nem"\n\teven\n'
    IDX[h] = lab
    return lab
# ---- 1. PLC lists
base = m['PLCLists'] - 0x200000
cnt = struct.unpack('>H', MMD[base:base + 2])[0] // 2
tbl = [struct.unpack('>H', MMD[base + 2 * x:base + 2 * x + 2])[0] for x in range(cnt)]
byaddr = {v: k for k, v in m.items() if k.startswith('PLC_')}
nm = {o: byaddr.get(0x200000 + base + o, f'PLC_Alt_{o:X}') for o in sorted(set(tbl))}
out = [f'{R}_PLCLists:'] + [f'\tdc.w\t{R}_{nm[o]}-{R}_PLCLists' for o in tbl] + ['']
unres = 0
for o in sorted(set(tbl)):
    x = base + o; n = struct.unpack('>H', MMD[x:x + 2])[0]
    out += [f'{R}_{nm[o]}:', f'\tdc.w\t${n:X}']
    for k in range(n + 1):
        p, v = struct.unpack('>LH', MMD[x + 2 + 6 * k:x + 8 + 6 * k]); l = art_label(p)
        if l is None: unres += 1; l = f'PLC_UNRESOLVED_{p:X}'
        out += [f'\tdc.l\t{l}', f'\tdc.w\t${v:X}']
    out.append('')
i = t.index(f'{R}_PLCLists:'); j = t.index('\tincbin\t"Level/Palmtree Panic/Data/Level/Padding')
t = t[:i] + '\n'.join(out) + '\n' + t[j:]
# ---- 2. duplicated incbin chunks
removed = 0; symf = f'src/MD Port/Zones/{R}/_symbols.txt'; symt = open(symf).read()
for mm in list(re.finditer(rf'^({R}_\w+):\n\tincbin\t"([^"]+)"\n(?:\teven\n)?', t, re.M)):
    q = 'src/' + mm[2]
    if not os.path.exists(q): continue
    h = hashlib.sha1(open(q, 'rb').read()).hexdigest()
    if h in IDX and IDX[h] != mm[1] and 'Padding' not in mm[2] and not re.search(r'Chunks|Layout|Collision|Demo|Foreground|Background', mm[2]):
        t = t.replace(mm.group(0), '', 1); t = re.sub(rf'\b{re.escape(mm[1])}\b', IDX[h], t); symt = re.sub(rf'\b{re.escape(mm[1])}\b', IDX[h], symt); removed += 1
open(f, 'w').write(t); open(poolf, 'w').write(pool); open(symf, 'w').write(symt)
print(f'{R}: PLC entries unresolved {unres}, shared pool size {pool.count("ArtPool_")//2 if False else pool.count("incbin")} files, duplicate chunks removed {removed}')
